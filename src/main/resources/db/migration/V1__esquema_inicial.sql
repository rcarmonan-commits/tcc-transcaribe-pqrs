-- =====================================================================
--  Transcaribe S.A. — Esquema de la base de datos del servicio de PQRS
--  Normalizado hasta Tercera Forma Normal (3FN).
--
--  Criterio de normalización aplicado:
--   1FN  Todos los atributos son atómicos; no hay grupos repetitivos
--        (los roles de un usuario viven en la tabla puente USUARIO_ROL).
--   2FN  Toda tabla tiene clave primaria simple y ningún atributo depende
--        de una parte de la clave (la única clave compuesta, USUARIO_ROL,
--        no tiene atributos no clave).
--   3FN  No hay dependencias transitivas: el plazo legal de respuesta vive
--        en TIPO_SOLICITUD y no se repite en PQRS; la capacidad nominal
--        vive en TIPO_VEHICULO y no en VEHICULO.
--
--  Decisión de diseño: los catálogos con atributos propios se modelan como
--  tablas (TIPO_SOLICITUD, ESTADO_PQRS, …). Los dominios cerrados sin
--  atributos adicionales (prioridad, estado operativo) se modelan como
--  columnas con restricción CHECK, para no multiplicar uniones sin valor.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Catálogos
-- ---------------------------------------------------------------------

CREATE TABLE tipo_documento (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(10)  NOT NULL,
    nombre      VARCHAR(80)  NOT NULL,
    CONSTRAINT uq_tipo_documento_codigo UNIQUE (codigo)
);

-- El plazo legal de respuesta es un atributo del tipo de solicitud,
-- no de cada PQRS: así se elimina la dependencia transitiva.
CREATE TABLE tipo_solicitud (
    id                      INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                  VARCHAR(30)  NOT NULL,
    nombre                  VARCHAR(80)  NOT NULL,
    dias_habiles_respuesta  INTEGER      NOT NULL,
    fundamento_legal        VARCHAR(160) NOT NULL,
    CONSTRAINT uq_tipo_solicitud_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipo_solicitud_dias   CHECK (dias_habiles_respuesta BETWEEN 1 AND 60)
);

CREATE TABLE canal_recepcion (
    id      INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(30) NOT NULL,
    nombre  VARCHAR(80) NOT NULL,
    CONSTRAINT uq_canal_recepcion_codigo UNIQUE (codigo)
);

CREATE TABLE categoria_pqrs (
    id               INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(40)  NOT NULL,
    nombre           VARCHAR(120) NOT NULL,
    prioridad_base   VARCHAR(10)  NOT NULL,
    activa           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_categoria_pqrs_codigo UNIQUE (codigo),
    CONSTRAINT ck_categoria_prioridad   CHECK (prioridad_base IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA'))
);

CREATE TABLE estado_pqrs (
    id        INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo    VARCHAR(30) NOT NULL,
    nombre    VARCHAR(80) NOT NULL,
    es_final  BOOLEAN     NOT NULL DEFAULT FALSE,
    orden     INTEGER     NOT NULL,
    CONSTRAINT uq_estado_pqrs_codigo UNIQUE (codigo)
);

CREATE TABLE tipo_vehiculo (
    id                INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(30) NOT NULL,
    nombre            VARCHAR(80) NOT NULL,
    capacidad_nominal INTEGER     NOT NULL,
    CONSTRAINT uq_tipo_vehiculo_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipo_vehiculo_cap    CHECK (capacidad_nominal > 0)
);

CREATE TABLE tipo_incidencia (
    id              INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(40)  NOT NULL,
    nombre          VARCHAR(120) NOT NULL,
    prioridad_base  VARCHAR(10)  NOT NULL,
    CONSTRAINT uq_tipo_incidencia_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipo_incidencia_prio   CHECK (prioridad_base IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA'))
);

CREATE TABLE rol (
    id           INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(40)  NOT NULL,
    nombre       VARCHAR(80)  NOT NULL,
    descripcion  VARCHAR(200) NOT NULL,
    CONSTRAINT uq_rol_codigo UNIQUE (codigo)
);

-- ---------------------------------------------------------------------
-- Seguridad: usuarios internos de Transcaribe
-- ---------------------------------------------------------------------

CREATE TABLE usuario (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario    VARCHAR(60)  NOT NULL,
    correo            VARCHAR(160) NOT NULL,
    hash_contrasena   VARCHAR(100) NOT NULL,
    nombres           VARCHAR(100) NOT NULL,
    apellidos         VARCHAR(100) NOT NULL,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    intentos_fallidos INTEGER      NOT NULL DEFAULT 0,
    bloqueado_hasta   TIMESTAMP    NULL,
    fecha_creacion    TIMESTAMP    NOT NULL,
    CONSTRAINT uq_usuario_nombre UNIQUE (nombre_usuario),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_intentos CHECK (intentos_fallidos >= 0)
);

-- Relación N:M resuelta con tabla puente (1FN: sin listas de roles).
CREATE TABLE usuario_rol (
    usuario_id BIGINT  NOT NULL,
    rol_id     INTEGER NOT NULL,
    CONSTRAINT pk_usuario_rol PRIMARY KEY (usuario_id, rol_id),
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_rol_rol     FOREIGN KEY (rol_id)     REFERENCES rol (id)
);

-- ---------------------------------------------------------------------
-- Operación: ciudadanos, flota y rutas
-- ---------------------------------------------------------------------

CREATE TABLE ciudadano (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento_id  INTEGER      NOT NULL,
    numero_documento   VARCHAR(20)  NOT NULL,
    nombres            VARCHAR(100) NOT NULL,
    apellidos          VARCHAR(100) NOT NULL,
    correo             VARCHAR(160) NOT NULL,
    telefono           VARCHAR(20)  NULL,
    fecha_registro     TIMESTAMP    NOT NULL,
    CONSTRAINT uq_ciudadano_documento UNIQUE (tipo_documento_id, numero_documento),
    CONSTRAINT fk_ciudadano_tipo_doc  FOREIGN KEY (tipo_documento_id) REFERENCES tipo_documento (id)
);

CREATE TABLE ruta (
    id      INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(20)  NOT NULL,
    nombre  VARCHAR(120) NOT NULL,
    origen  VARCHAR(120) NOT NULL,
    destino VARCHAR(120) NOT NULL,
    activa  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_ruta_codigo UNIQUE (codigo)
);

CREATE TABLE vehiculo (
    id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa              VARCHAR(10) NOT NULL,
    numero_interno     VARCHAR(10) NOT NULL,
    tipo_vehiculo_id   INTEGER     NOT NULL,
    estado_operativo   VARCHAR(20) NOT NULL,
    fecha_vinculacion  DATE        NOT NULL,
    CONSTRAINT uq_vehiculo_placa    UNIQUE (placa),
    CONSTRAINT uq_vehiculo_interno  UNIQUE (numero_interno),
    CONSTRAINT fk_vehiculo_tipo     FOREIGN KEY (tipo_vehiculo_id) REFERENCES tipo_vehiculo (id),
    CONSTRAINT ck_vehiculo_estado   CHECK (estado_operativo IN ('OPERATIVO', 'EN_MANTENIMIENTO', 'FUERA_DE_SERVICIO'))
);

-- ---------------------------------------------------------------------
-- Núcleo del dominio: PQRS
-- ---------------------------------------------------------------------

CREATE TABLE pqrs (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    radicado             VARCHAR(20)   NOT NULL,
    tipo_solicitud_id    INTEGER       NOT NULL,
    categoria_id         INTEGER       NOT NULL,
    canal_id             INTEGER       NOT NULL,
    estado_id            INTEGER       NOT NULL,
    ciudadano_id         BIGINT        NOT NULL,
    ruta_id              INTEGER       NULL,
    vehiculo_id          BIGINT        NULL,
    usuario_asignado_id  BIGINT        NULL,
    prioridad            VARCHAR(10)   NOT NULL,
    asunto               VARCHAR(180)  NOT NULL,
    descripcion          VARCHAR(4000) NOT NULL,
    respuesta            VARCHAR(4000) NULL,
    fecha_radicacion     TIMESTAMP     NOT NULL,
    fecha_vencimiento    DATE          NOT NULL,
    fecha_respuesta      TIMESTAMP     NULL,
    -- Hecho registrado en el momento de responder, no derivado al consultar.
    -- Evita comparar TIMESTAMP con DATE en la consulta del indicador legal,
    -- que es justo donde el SQL deja de ser portable entre motores.
    respondida_en_plazo  BOOLEAN       NULL,
    CONSTRAINT uq_pqrs_radicado     UNIQUE (radicado),
    CONSTRAINT fk_pqrs_tipo         FOREIGN KEY (tipo_solicitud_id)   REFERENCES tipo_solicitud (id),
    CONSTRAINT fk_pqrs_categoria    FOREIGN KEY (categoria_id)        REFERENCES categoria_pqrs (id),
    CONSTRAINT fk_pqrs_canal        FOREIGN KEY (canal_id)            REFERENCES canal_recepcion (id),
    CONSTRAINT fk_pqrs_estado       FOREIGN KEY (estado_id)           REFERENCES estado_pqrs (id),
    CONSTRAINT fk_pqrs_ciudadano    FOREIGN KEY (ciudadano_id)        REFERENCES ciudadano (id),
    CONSTRAINT fk_pqrs_ruta         FOREIGN KEY (ruta_id)             REFERENCES ruta (id),
    CONSTRAINT fk_pqrs_vehiculo     FOREIGN KEY (vehiculo_id)         REFERENCES vehiculo (id),
    CONSTRAINT fk_pqrs_asignado     FOREIGN KEY (usuario_asignado_id) REFERENCES usuario (id),
    CONSTRAINT ck_pqrs_prioridad    CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA'))
);

CREATE INDEX ix_pqrs_ciudadano   ON pqrs (ciudadano_id);
CREATE INDEX ix_pqrs_estado      ON pqrs (estado_id);
CREATE INDEX ix_pqrs_vencimiento ON pqrs (fecha_vencimiento);
CREATE INDEX ix_pqrs_radicacion  ON pqrs (fecha_radicacion);

-- Bitácora inmutable de transiciones: soporta la trazabilidad exigida
-- por la rendición de cuentas y el control A09:2021 de OWASP.
CREATE TABLE seguimiento_pqrs (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pqrs_id            BIGINT        NOT NULL,
    estado_anterior_id INTEGER       NULL,
    estado_nuevo_id    INTEGER       NOT NULL,
    usuario_id         BIGINT        NULL,
    observacion        VARCHAR(1000) NOT NULL,
    fecha_registro     TIMESTAMP     NOT NULL,
    CONSTRAINT fk_seg_pqrs      FOREIGN KEY (pqrs_id)            REFERENCES pqrs (id) ON DELETE CASCADE,
    CONSTRAINT fk_seg_anterior  FOREIGN KEY (estado_anterior_id) REFERENCES estado_pqrs (id),
    CONSTRAINT fk_seg_nuevo     FOREIGN KEY (estado_nuevo_id)    REFERENCES estado_pqrs (id),
    CONSTRAINT fk_seg_usuario   FOREIGN KEY (usuario_id)         REFERENCES usuario (id)
);

CREATE INDEX ix_seguimiento_pqrs ON seguimiento_pqrs (pqrs_id);

-- ---------------------------------------------------------------------
-- Incidencias de flota
-- ---------------------------------------------------------------------

CREATE TABLE incidencia (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consecutivo         VARCHAR(20)   NOT NULL,
    vehiculo_id         BIGINT        NOT NULL,
    ruta_id             INTEGER       NULL,
    tipo_incidencia_id  INTEGER       NOT NULL,
    pqrs_id             BIGINT        NULL,
    usuario_reporta_id  BIGINT        NULL,
    descripcion         VARCHAR(2000) NOT NULL,
    estado              VARCHAR(20)   NOT NULL,
    fecha_hora          TIMESTAMP     NOT NULL,
    CONSTRAINT uq_incidencia_consecutivo UNIQUE (consecutivo),
    CONSTRAINT fk_inc_vehiculo FOREIGN KEY (vehiculo_id)        REFERENCES vehiculo (id),
    CONSTRAINT fk_inc_ruta     FOREIGN KEY (ruta_id)            REFERENCES ruta (id),
    CONSTRAINT fk_inc_tipo     FOREIGN KEY (tipo_incidencia_id) REFERENCES tipo_incidencia (id),
    CONSTRAINT fk_inc_pqrs     FOREIGN KEY (pqrs_id)            REFERENCES pqrs (id),
    CONSTRAINT fk_inc_usuario  FOREIGN KEY (usuario_reporta_id) REFERENCES usuario (id),
    CONSTRAINT ck_inc_estado   CHECK (estado IN ('REPORTADA', 'EN_ATENCION', 'CERRADA'))
);

CREATE INDEX ix_incidencia_vehiculo ON incidencia (vehiculo_id);
CREATE INDEX ix_incidencia_fecha    ON incidencia (fecha_hora);

-- ---------------------------------------------------------------------
-- Soporte: calendario de días hábiles y consecutivos
-- ---------------------------------------------------------------------

-- Festivos de Colombia (Ley 51 de 1983). Persistirlos evita incrustar
-- el calendario en el código y permite ajustarlo sin redesplegar.
CREATE TABLE festivo (
    fecha        DATE        PRIMARY KEY,
    descripcion  VARCHAR(80) NOT NULL
);

-- Consecutivo anual del radicado; el bloqueo pesimista sobre esta fila
-- garantiza unicidad bajo concurrencia sin depender del motor.
CREATE TABLE consecutivo_radicado (
    anio          INTEGER NOT NULL PRIMARY KEY,
    ultimo_valor  BIGINT  NOT NULL,
    CONSTRAINT ck_consecutivo_valor CHECK (ultimo_valor >= 0)
);

-- Registro de eventos de seguridad (OWASP A09:2021).
-- La IP se almacena como hash: trazabilidad sin dato personal en claro.
CREATE TABLE auditoria_acceso (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(60)  NOT NULL,
    accion         VARCHAR(40)  NOT NULL,
    recurso        VARCHAR(200) NOT NULL,
    ip_hash        VARCHAR(64)  NOT NULL,
    exitoso        BOOLEAN      NOT NULL,
    fecha          TIMESTAMP    NOT NULL
);

CREATE INDEX ix_auditoria_fecha   ON auditoria_acceso (fecha);
CREATE INDEX ix_auditoria_usuario ON auditoria_acceso (nombre_usuario);
